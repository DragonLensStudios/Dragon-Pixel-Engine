using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Globalization;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace DragonPixel.PocC.Generator;

[Generator(LanguageNames.CSharp)]
public sealed class ComponentManifestGenerator : IIncrementalGenerator
{
    private const string ComponentAttributeName = "DragonPixel.PocC.DpeComponentAttribute";
    private const string PropertyAttributeName = "DragonPixel.PocC.DpePropertyAttribute";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var descriptors = context.SyntaxProvider.ForAttributeWithMetadataName(
                ComponentAttributeName,
                static (node, _) => node is ClassDeclarationSyntax,
                static (attributeContext, _) => ReadComponent(attributeContext))
            .Where(static descriptor => descriptor is not null)
            .Collect();

        context.RegisterSourceOutput(descriptors, static (productionContext, values) =>
        {
            var components = values
                .Where(static value => value is not null)
                .Select(static value => value!)
                .OrderBy(static value => value.TypeId, StringComparer.Ordinal)
                .ToArray();
            var json = BuildManifest(components);
            var source = "// <auto-generated />\n#nullable enable\nnamespace DragonPixel.PocC.Generated\n{\n    public static class GeneratedComponentManifest\n    {\n        public const string Json = "
                + ToCSharpString(json)
                + ";\n    }\n}\n";
            productionContext.AddSource("GeneratedComponentManifest.g.cs", SourceText.From(source, Encoding.UTF8));
        });
    }

    private static ComponentDescriptor? ReadComponent(GeneratorAttributeSyntaxContext context)
    {
        if (context.TargetSymbol is not INamedTypeSymbol componentSymbol || context.Attributes.Length == 0)
        {
            return null;
        }

        var attribute = context.Attributes[0];
        if (attribute.ConstructorArguments.Length != 5)
        {
            return null;
        }

        var typeId = attribute.ConstructorArguments[0].Value as string;
        var qualifiedName = attribute.ConstructorArguments[1].Value as string;
        var displayName = attribute.ConstructorArguments[2].Value as string;
        var schemaVersion = attribute.ConstructorArguments[3].Value as int?;
        var owner = attribute.ConstructorArguments[4].Value as string;
        if (typeId is null || qualifiedName is null || displayName is null || schemaVersion is null || owner is null)
        {
            return null;
        }

        var properties = new List<PropertyDescriptor>();
        foreach (var propertySymbol in componentSymbol.GetMembers().OfType<IPropertySymbol>())
        {
            var propertyAttribute = propertySymbol.GetAttributes().FirstOrDefault(static candidate =>
                candidate.AttributeClass?.ToDisplayString() == PropertyAttributeName);
            if (propertyAttribute is null || propertyAttribute.ConstructorArguments.Length != 3)
            {
                continue;
            }

            var propertyId = propertyAttribute.ConstructorArguments[0].Value as string;
            var propertyDisplayName = propertyAttribute.ConstructorArguments[1].Value as string;
            var valueType = propertyAttribute.ConstructorArguments[2].Value as string;
            if (propertyId is null || propertyDisplayName is null || valueType is null)
            {
                continue;
            }

            var order = 0;
            var readOnly = false;
            foreach (var namedArgument in propertyAttribute.NamedArguments)
            {
                if (namedArgument.Key == "Order" && namedArgument.Value.Value is int orderValue)
                {
                    order = orderValue;
                }
                else if (namedArgument.Key == "ReadOnly" && namedArgument.Value.Value is bool readOnlyValue)
                {
                    readOnly = readOnlyValue;
                }
            }

            properties.Add(new PropertyDescriptor(propertyId, propertyDisplayName, valueType, order, readOnly));
        }

        properties.Sort(static (left, right) =>
        {
            var orderComparison = left.Order.CompareTo(right.Order);
            return orderComparison != 0
                ? orderComparison
                : StringComparer.Ordinal.Compare(left.PropertyId, right.PropertyId);
        });
        return new ComponentDescriptor(typeId, qualifiedName, displayName, schemaVersion.Value, owner, properties.ToImmutableArray());
    }

    private static string BuildManifest(IReadOnlyList<ComponentDescriptor> components)
    {
        var builder = new StringBuilder();
        builder.Append("{\"$schema\":\"https://dragonpixel.dev/schemas/v2/component-metadata.schema.json\",\"format\":\"dpe.component-metadata\",\"formatVersion\":2,\"generatorVersion\":\"1\",\"components\":[");
        for (var componentIndex = 0; componentIndex < components.Count; componentIndex++)
        {
            if (componentIndex > 0)
            {
                builder.Append(',');
            }

            var component = components[componentIndex];
            builder.Append("{\"typeId\":").Append(ToJsonString(component.TypeId))
                .Append(",\"qualifiedName\":").Append(ToJsonString(component.QualifiedName))
                .Append(",\"displayName\":").Append(ToJsonString(component.DisplayName))
                .Append(",\"schemaVersion\":").Append(component.SchemaVersion.ToString(CultureInfo.InvariantCulture))
                .Append(",\"owner\":").Append(ToJsonString(component.Owner))
                .Append(",\"properties\":[");

            for (var propertyIndex = 0; propertyIndex < component.Properties.Length; propertyIndex++)
            {
                if (propertyIndex > 0)
                {
                    builder.Append(',');
                }

                var property = component.Properties[propertyIndex];
                builder.Append("{\"propertyId\":").Append(ToJsonString(property.PropertyId))
                    .Append(",\"displayName\":").Append(ToJsonString(property.DisplayName))
                    .Append(",\"valueType\":").Append(ToJsonString(property.ValueType))
                    .Append(",\"order\":").Append(property.Order.ToString(CultureInfo.InvariantCulture))
                    .Append(",\"readOnly\":").Append(property.ReadOnly ? "true" : "false")
                    .Append('}');
            }

            builder.Append("]}");
        }

        return builder.Append("]}").ToString();
    }

    private static string ToJsonString(string value)
    {
        var builder = new StringBuilder(value.Length + 2).Append('"');
        foreach (var character in value)
        {
            switch (character)
            {
                case '"': builder.Append("\\\""); break;
                case '\\': builder.Append("\\\\"); break;
                case '\b': builder.Append("\\b"); break;
                case '\f': builder.Append("\\f"); break;
                case '\n': builder.Append("\\n"); break;
                case '\r': builder.Append("\\r"); break;
                case '\t': builder.Append("\\t"); break;
                default:
                    if (character < ' ')
                    {
                        builder.Append("\\u").Append(((int)character).ToString("x4", CultureInfo.InvariantCulture));
                    }
                    else
                    {
                        builder.Append(character);
                    }
                    break;
            }
        }

        return builder.Append('"').ToString();
    }

    private static string ToCSharpString(string value) => ToJsonString(value);

    private sealed class ComponentDescriptor
    {
        public ComponentDescriptor(
            string typeId,
            string qualifiedName,
            string displayName,
            int schemaVersion,
            string owner,
            ImmutableArray<PropertyDescriptor> properties)
        {
            TypeId = typeId;
            QualifiedName = qualifiedName;
            DisplayName = displayName;
            SchemaVersion = schemaVersion;
            Owner = owner;
            Properties = properties;
        }

        public string TypeId { get; }
        public string QualifiedName { get; }
        public string DisplayName { get; }
        public int SchemaVersion { get; }
        public string Owner { get; }
        public ImmutableArray<PropertyDescriptor> Properties { get; }
    }

    private sealed class PropertyDescriptor
    {
        public PropertyDescriptor(string propertyId, string displayName, string valueType, int order, bool readOnly)
        {
            PropertyId = propertyId;
            DisplayName = displayName;
            ValueType = valueType;
            Order = order;
            ReadOnly = readOnly;
        }

        public string PropertyId { get; }
        public string DisplayName { get; }
        public string ValueType { get; }
        public int Order { get; }
        public bool ReadOnly { get; }
    }
}
